"""Claude Code runtime helpers: startup check, transcript recorder and Orchestrator entry writer.

Fixtures under tests/fixtures/claude are sanitized record skeletons of real Claude Code subagent
transcripts (CLI final-text form; desktop auto-mode SubagentHandback form with coordinator and peer
continuations). Tests inject report text at their __REPORT__ placeholders, including valid wrappers
generated by flow_fixtures; negative cases alter real records and say so where they do. Recording runs
the Claude copy in a subprocess so the Claude runtime files, not the Codex modules cached in this
process, are exercised.
"""
from copy import deepcopy
from pathlib import Path
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / ".codex/skills/orchestrator-flow/scripts"))
from workflow_artifacts import json_values_equal
from flow_fixtures import Flow

CLAUDE = ROOT / ".claude/skills/orchestrator-flow"
CHECK = CLAUDE / "scripts/check_claude_code.py"
LOG_SCRIPT = CLAUDE / "scripts/claude_log.py"
FIXTURES = ROOT / "tests/fixtures/claude"
UNICODE = "tasks 1–7; café; 漢字; 😀; é; a < b && c > d; \"quoted\""


def planner_handoff(summary=UNICODE):
    """Return a log awaiting the Planner's requirements return, and that actual return."""
    flow = Flow(platform="claude-code")
    previous = deepcopy(flow.log)
    flow.spec_output("requirements")
    wrapper = flow.log["history"][-1]["spec_change_wrapper"]
    wrapper["summary"] = summary
    return previous, wrapper


def coder_coordination():
    """Return a log with an active Coder assignment, and a Coder coordination report."""
    from test_recovery_and_reviews import coding_flow
    flow = coding_flow()
    previous = deepcopy(flow.log)
    blocker = {"id": "live-check", "operation": "remote validation", "task_ids": ["2"], "reason": "Access needs user authority.",
               "attempts": [], "evidence": ["No live operation was attempted."], "depends_on": ["external access"],
               "independent_task_ids": ["1"], "required_authorization": "One bounded live check."}
    details = flow.code_output(consolidated=False, blockers=[blocker])
    details["task_progress"] = [{"task_id": str(task), "status": "pending", "evidence": "Recorded pending work.", "disposition_ref": None}
                                for task in (1, 2)]
    return previous, details


def transcript_text(fixture, report, earlier="An earlier report from a previous run."):
    text = (FIXTURES / fixture).read_text(encoding="utf-8")
    return text.replace('"__REPORT__"', json.dumps(report, ensure_ascii=False)).replace('"__REPORT_1__"', json.dumps(earlier))


def dumps(value):
    return json.dumps(value, ensure_ascii=False)


class ClaudeLogTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.log = self.tmp / "task_log.json"

    def write_log(self, log):
        self.log.write_text(json.dumps(log, indent=2) + "\n", encoding="utf-8")

    def write_transcript(self, text, name="agent-a1b2c3.jsonl"):
        path = self.tmp / name
        path.write_text(text, encoding="utf-8")
        return path

    def run_log(self, *args, stdin=None, env=None):
        environment = {key: value for key, value in os.environ.items() if not key.startswith("CLAUDE_")}
        environment.update(env or {})
        return subprocess.run([sys.executable, "-B", str(LOG_SCRIPT), *args], input=stdin, capture_output=True, text=True,
                              encoding="utf-8", cwd=self.tmp, env=environment)

    def record(self, transcript, *extra, **kwargs):
        return self.run_log("record-return", "--log", str(self.log), "--transcript", str(transcript), *extra, **kwargs)

    def assertRecorded(self, result, wrapper, key="spec_change_wrapper"):
        self.assertEqual(result.returncode, 0, result.stderr)
        recorded = json.loads(self.log.read_text(encoding="utf-8"))["history"][-1]
        self.assertTrue(json_values_equal(recorded[key], wrapper))
        return json.loads(result.stdout)

    def assertRejected(self, result, category, before):
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn(f"INVALID: {category}", result.stderr)
        self.assertEqual(self.log.read_bytes(), before, "A rejected return must leave the log untouched")

    def test_final_text_return_is_recorded_exactly(self):
        previous, wrapper = planner_handoff()
        self.write_log(previous)
        summary = self.assertRecorded(self.record(self.write_transcript(transcript_text("cli-final-text.jsonl", dumps(wrapper)))), wrapper)
        self.assertEqual(summary["recorded"], {"event_id": "2", "event": "spec-updated", "actor": "Planner"})
        self.assertEqual(summary["status"], "spec_in_progress")
        self.assertEqual(summary["workflow_action"], "obtain_requirements_approval")
        self.assertEqual(summary["source"], "transcript")

    def test_handback_return_uses_the_latest_run_and_reports_observed_capability(self):
        for fixture in ("desktop-handback-continued.jsonl", "desktop-peer-continued.jsonl"):
            with self.subTest(fixture=fixture):
                previous, wrapper = planner_handoff()
                self.write_log(previous)
                summary = self.assertRecorded(self.record(self.write_transcript(transcript_text(fixture, dumps(wrapper)))), wrapper)
                # The fixture agents ran on Haiku at max effort; the log records example-model at high.
                self.assertEqual(summary["observed"], {"model": "claude-haiku-5-5", "effort": "max"})
                self.assertIn("observed model claude-haiku-5-5, recorded example-model", summary["capability_note"])

    def test_large_return_is_recorded_from_the_transcript(self):
        previous, wrapper = planner_handoff(summary=UNICODE * 2500)
        self.assertGreater(len(dumps(wrapper)), 82_000)
        self.write_log(previous)
        self.assertRecorded(self.record(self.write_transcript(transcript_text("desktop-handback-continued.jsonl", dumps(wrapper)))), wrapper)

    def test_unfinished_runs_are_not_recorded(self):
        previous, wrapper = planner_handoff()
        self.write_log(previous)
        before = self.log.read_bytes()
        lines = transcript_text("desktop-handback-continued.jsonl", dumps(wrapper)).splitlines(keepends=True)
        # Cut after the coordinator continuation (record 26) and after the harness reminder (record 38).
        for cut in (26, 38):
            with self.subTest(cut=cut):
                self.assertRejected(self.record(self.write_transcript("".join(lines[:cut]))), "no_completed_report", before)
        with self.subTest(case="partial last line"):
            self.assertRejected(self.record(self.write_transcript("".join(lines) + '{"type": "assist')), "no_completed_report", before)
        with self.subTest(case="max_tokens"):
            # Altered real record: the final text stops at the output limit instead of end_turn.
            text = transcript_text("cli-final-text.jsonl", dumps(wrapper)).replace('"stop_reason": "end_turn"', '"stop_reason": "max_tokens"')
            self.assertRejected(self.record(self.write_transcript(text)), "no_completed_report", before)

    def test_unusable_reports_and_layouts_are_rejected(self):
        previous, wrapper = planner_handoff()
        self.write_log(previous)
        before = self.log.read_bytes()
        self.assertRejected(self.record(self.write_transcript(transcript_text("cli-final-text.jsonl", "Here is the report you asked for."))),
                            "report_not_json", before)
        # Altered real record: a handback the harness did not deliver.
        refused = transcript_text("desktop-handback-continued.jsonl", dumps(wrapper)).replace('\\"success\\":true', '\\"success\\":false')
        self.assertRejected(self.record(self.write_transcript(refused)), "report_not_delivered", before)
        lines = transcript_text("cli-final-text.jsonl", dumps(wrapper)).splitlines(keepends=True)
        broken = json.loads(lines[-2])
        broken["message"] = "unexpected"
        self.assertRejected(self.record(self.write_transcript("".join(lines[:-2]) + dumps(broken) + "\n")), "transcript_layout_changed", before)
        self.assertRejected(self.record(self.write_transcript("".join(lines[1:]))), "transcript_layout_changed", before)
        # A return for another assignment is invalid native output, not a transcript problem.
        other = deepcopy(wrapper)
        other["context"]["attempt"] = 2
        self.assertRejected(self.record(self.write_transcript(transcript_text("cli-final-text.jsonl", dumps(other)))), "invalid_native_output", before)

    def test_already_recorded_return_writes_nothing(self):
        previous, wrapper = planner_handoff()
        self.write_log(previous)
        transcript = self.write_transcript(transcript_text("cli-final-text.jsonl", dumps(wrapper)))
        self.assertRecorded(self.record(transcript), wrapper)
        before = self.log.read_bytes()
        result = self.record(transcript)
        self.assertRejected(result, "already_recorded", before)
        self.assertIn("event 2", result.stderr)

    def test_inline_returns_must_be_unaltered(self):
        previous, wrapper = planner_handoff()
        self.write_log(previous)
        before = self.log.read_bytes()
        # Desktop indents every line of an inline hand-back; whitespace does not change the JSON value.
        indented = "\n".join("  " + line for line in json.dumps(wrapper, ensure_ascii=False, indent=2).splitlines())
        for altered in (dumps(wrapper).replace(" < ", " &lt; "), "[harness: control tags neutralized]\n" + dumps(wrapper),
                        dumps(wrapper).replace("quoted", "<\\task-notification>")):
            with self.subTest(altered=altered[:40]):
                result = self.run_log("record-return", "--log", str(self.log), "--stdin", stdin=altered)
                self.assertRejected(result, "inline_text_altered", before)
        result = self.run_log("record-return", "--log", str(self.log), "--stdin", stdin=indented)
        self.assertEqual(self.assertRecorded(result, wrapper)["source"], "stdin")

    def test_transcripts_are_found_in_this_session_then_this_project(self):
        previous, wrapper = planner_handoff()
        config = self.tmp / "config"
        project = config / "projects/-work-example-project"
        session, other = "11111111-1111-4111-8111-111111111111", "22222222-2222-4222-8222-222222222222"
        text = transcript_text("cli-final-text.jsonl", dumps(wrapper))
        env = {"CLAUDE_CONFIG_DIR": str(config), "CLAUDE_CODE_SESSION_ID": session}
        (project / session / "subagents").mkdir(parents=True)
        (project / session / "subagents/agent-a1b2c3.jsonl").write_text(text, encoding="utf-8")
        self.write_log(previous)
        self.assertRecorded(self.run_log("record-return", "--log", str(self.log), "--agent-id", "a1b2c3", env=env), wrapper)
        # The current session folder lacks the agent; another session of the same project holds it.
        shutil.rmtree(project / session)
        (project / f"{session}.jsonl").write_text("{}\n", encoding="utf-8")
        (project / other / "subagents").mkdir(parents=True)
        (project / other / "subagents/agent-a1b2c3.jsonl").write_text(text, encoding="utf-8")
        self.write_log(previous)
        self.assertRecorded(self.run_log("record-return", "--log", str(self.log), "--agent-id", "a1b2c3", env=env), wrapper)
        before = self.log.read_bytes()
        for args, environment in ((("--agent-id", "missing"), env), (("--agent-id", "a1b2c3"), {"CLAUDE_CONFIG_DIR": str(config)}),
                                  (("--agent-id", "../escape"), env)):
            with self.subTest(args=args):
                result = self.run_log("record-return", "--log", str(self.log), *args, env=environment)
                self.assertEqual(result.returncode, 1)
                self.assertEqual(self.log.read_bytes(), before)

    def test_coordination_report_is_recorded_as_coding_updated(self):
        previous, details = coder_coordination()
        self.write_log(previous)
        result = self.record(self.write_transcript(transcript_text("cli-final-text.jsonl", dumps(details))), "--coordination")
        self.assertEqual(result.returncode, 0, result.stderr)
        entry = json.loads(self.log.read_text(encoding="utf-8"))["history"][-1]
        self.assertEqual((entry["event"], entry["actor"], entry["requestor"], entry["status"]), ("coding-updated", "Coder", "Planner", "coding_in_progress"))
        self.assertTrue(json_values_equal(entry["details"], details))
        self.assertEqual(json.loads(result.stdout)["blockers"], [{"id": "live-check", "reason": "Access needs user authority."}])

    def test_orchestrator_entries_derive_metadata_and_validate_before_writing(self):
        flow = Flow(platform="claude-code")
        flow.spec_output("requirements")
        previous = deepcopy(flow.log)
        flow.approve("requirements")
        approval = flow.log["history"][-1]
        self.write_log(previous)
        entry = {key: approval[key] for key in ("actor", "requestor", "event", "details")}
        result = self.run_log("append-entry", "--log", str(self.log), stdin=dumps(entry))
        self.assertEqual(result.returncode, 0, result.stderr)
        written = json.loads(self.log.read_text(encoding="utf-8"))
        self.assertEqual(written["history"][:-1], previous["history"])
        self.assertEqual({k: v for k, v in written["history"][-1].items() if k != "timestamp"}, {k: v for k, v in approval.items() if k != "timestamp"})
        self.assertEqual(json.loads(result.stdout)["workflow_action"], "continue_planner_design")
        # An override also updates the effective configuration fields.
        helper = {"model": "haiku", "reasoning_effort": "low"}
        override = {"actor": "User", "requestor": "User", "event": "user-override", "details": {
            "changes": [{"target": "/capability/roles/helpers", "previous": written["capability"]["roles"]["helpers"], "new": helper}],
            "rationale": "Cheaper test runs.", "user_statement": "Use Haiku at low effort for test runs."}}
        result = self.run_log("append-entry", "--log", str(self.log), stdin=dumps(override))
        self.assertEqual(result.returncode, 0, result.stderr)
        written = json.loads(self.log.read_text(encoding="utf-8"))
        self.assertEqual(written["capability"]["roles"]["helpers"], helper)
        before = self.log.read_bytes()
        for invalid in ({**entry, "actor": "Orchestrator"}, {**entry, "status": "spec_ready"}, {key: entry[key] for key in ("actor", "event", "details")}):
            with self.subTest(invalid=sorted(invalid)):
                self.assertRejected(self.run_log("append-entry", "--log", str(self.log), stdin=dumps(invalid)), "invalid_entry", before)


class ClaudeStartupCheckTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.skill = self.tmp / "skill"
        (self.skill / "scripts").mkdir(parents=True)
        shutil.copy2(CHECK, self.skill / "scripts/check_claude_code.py")
        self.fake_python("exit 0")

    def executable(self, path, body):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("#!/bin/sh\n" + body + "\n", encoding="utf-8")
        path.chmod(0o755)
        return path

    def fake_python(self, body):
        python = self.skill / ".venv/bin/python"
        if python.is_symlink() or python.exists():
            python.unlink()
        return self.executable(python, body)

    def check(self, env):
        environment = {key: value for key, value in os.environ.items() if not key.startswith("CLAUDE_")}
        environment.update(env)
        result = subprocess.run([sys.executable, str(self.skill / "scripts/check_claude_code.py")], capture_output=True, text=True,
                                encoding="utf-8", env=environment, cwd=self.tmp)
        self.assertEqual(result.returncode, 0, "The startup check must always exit 0")
        return result.stdout.splitlines()

    def claude(self, output, status=0, path="bin/claude"):
        return str(self.executable(self.tmp / path, f"echo '{output}'\nexit {status}"))

    def test_running_version_is_compared_with_the_minimum(self):
        for version, verdict in (("2.1.295", "too_old"), ("2.1.296", "supported"), ("2.1.300", "supported"), ("2.2.0", "supported")):
            with self.subTest(version=version):
                lines = self.check({"CLAUDE_CODE_EXECPATH": self.claude(f"{version} (Claude Code)"), "CLAUDE_CODE_ENTRYPOINT": "cli"})
                self.assertEqual(lines[0], f"Claude Code: {verdict} (running {version} from the Claude Code CLI; minimum 2.1.296)")
        lines = self.check({"CLAUDE_CODE_EXECPATH": self.claude("2.1.295 (Claude Code)", path="Library/Application Support/Claude/claude-code/2.1.295/claude"),
                            "CLAUDE_CODE_ENTRYPOINT": "cli"})
        self.assertEqual(lines[1], "Orchestrator Flow requires Claude Code 2.1.296 or newer. This session is running Claude Code 2.1.295 "
                                   "(Claude desktop app). Update Claude Code, then start a new session: in a terminal run `claude update`; "
                                   "for the desktop app, update the Claude app.")

    def test_unknown_versions_are_reported_not_fatal(self):
        unreadable = self.tmp / "not-executable"
        unreadable.write_text("2.1.300 (Claude Code)", encoding="utf-8")
        for name, env in (("missing variable", {}), ("garbage", {"CLAUDE_CODE_EXECPATH": self.claude("nonsense")}),
                          ("failed run", {"CLAUDE_CODE_EXECPATH": self.claude("2.1.300 (Claude Code)", status=3)}),
                          ("not executable", {"CLAUDE_CODE_EXECPATH": str(unreadable)})):
            with self.subTest(case=name):
                self.assertTrue(self.check(env)[0].startswith("Claude Code: unknown ("))

    def test_runtime_venv_problems_include_setup_commands(self):
        env = {"CLAUDE_CODE_EXECPATH": self.claude("2.1.300 (Claude Code)")}
        self.assertIn("Runtime venv: ok", self.check(env))
        self.fake_python("echo \"ModuleNotFoundError: No module named 'jsonschema'\" >&2\nexit 1")
        self.assertIn("Runtime venv: missing_dependencies. Set it up before starting the workflow:", self.check(env))
        python = self.skill / ".venv/bin/python"
        python.unlink()
        python.symlink_to(self.tmp / "removed-interpreter")
        lines = self.check(env)
        self.assertIn("Runtime venv: broken. Set it up before starting the workflow:", lines)
        self.assertIn(f'  python3 -m venv --clear "{(self.skill / ".venv").resolve()}"', lines)
        shutil.rmtree(self.skill / ".venv")
        self.assertIn("Runtime venv: missing. Set it up before starting the workflow:", self.check(env))

    def test_defeating_overrides_are_disclosed(self):
        env = {"CLAUDE_CODE_EXECPATH": self.claude("2.1.300 (Claude Code)")}
        self.assertIn("Per-call overrides: none", self.check(env))
        lines = self.check({**env, "CLAUDE_CODE_SUBAGENT_MODEL_FORCE": "1", "CLAUDE_CODE_SUBAGENT_MODEL": "sonnet", "CLAUDE_CODE_EFFORT_LEVEL": "low"})
        self.assertIn("Per-call overrides: CLAUDE_CODE_SUBAGENT_MODEL_FORCE=1, CLAUDE_CODE_SUBAGENT_MODEL=sonnet, CLAUDE_CODE_EFFORT_LEVEL=low", lines)


if __name__ == "__main__":
    unittest.main()
